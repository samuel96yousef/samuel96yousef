#!/usr/bin/env python3
"""Turn a hymn book (PDF) into the page images of the Alhan section.

The hymns are written with hazzat, the hand-drawn marks above the words that
carry the melody. Those are drawings, not text, so the app shows the book's
own pages. Each page is cropped inside the book's frame, trimmed of empty
space above and below, and stored as an ink mask: the ink is the alpha
channel, so the app tints it with the reading colours (paper, sepia, night).

The table of contents is written by hand in scripts/alhan/<book>.json, with
the book's page numbers; this script turns those into page indices and writes
assets/alhan/index.ts.

Needs pdftoppm (poppler) and Pillow with WebP.

Usage:
    python3 scripts/alhan_pages.py <book.pdf> <book-id>
"""

import json
import os
import shutil
import subprocess
import sys
import tempfile

import numpy as np
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'assets', 'alhan')

# Inside the frame of a page rendered at 200 dpi (the frame's lines are at
# x 268-1344 and y 69-1721; the footer with the page number starts at y 1694).
DPI = 200
CROP = (278, 78, 1337, 1690)
PAD = 28


def page_image(png):
    gray = Image.open(png).convert('L').crop(CROP)
    a = np.array(gray)
    rows = np.where((a < 200).sum(1) > 2)[0]
    if len(rows):
        a = a[max(0, rows[0] - PAD):min(a.shape[0], rows[-1] + PAD)]
    # Ink is what is dark: the alpha channel; sixteen levels are smooth enough and pack small.
    alpha = ((255 - a.astype(np.int32)) // 16 * 17).clip(0, 255).astype(np.uint8)
    rgba = np.zeros((*alpha.shape, 4), np.uint8)
    rgba[..., 3] = alpha
    return Image.fromarray(rgba, 'RGBA')


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    pdf, book = sys.argv[1], sys.argv[2]
    with open(os.path.join(ROOT, 'scripts', 'alhan', f'{book}.json'), encoding='utf-8') as f:
        spec = json.load(f)

    out = os.path.join(OUT, book)
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(out)

    first, last = spec['pdfPages']
    pages = []
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(['pdftoppm', '-r', str(DPI), '-gray', '-png', '-f', str(first), '-l', str(last), pdf, os.path.join(tmp, 'p')], check=True)
        for name in sorted(os.listdir(tmp)):
            pdf_page = int(name[2:-4])
            img = page_image(os.path.join(tmp, name))
            file = f'{pdf_page:03d}.webp'
            img.save(os.path.join(out, file), lossless=True, quality=100, method=6)
            # The number printed on the page: the book skips one between its front matter and the hymns.
            printed = pdf_page + spec['printedOffset'] if pdf_page < spec['offsetUntil'] else pdf_page
            pages.append({'file': file, 'w': img.width, 'h': img.height, 'no': printed})

        # The cover, in colour and small, for the book's card.
        subprocess.run(['pdftoppm', '-r', '100', '-png', '-singlefile', '-f', str(spec['cover']), '-l', str(spec['cover']), pdf, os.path.join(tmp, 'cover')], check=True)
        cover = Image.open(os.path.join(tmp, 'cover.png')).convert('RGB')
        cover.thumbnail((360, 480))
        cover.save(os.path.join(out, 'cover.webp'), quality=82, method=6)

    index_of = {p['no']: i for i, p in enumerate(pages)}
    parts = []
    for part in spec['parts']:
        items = []
        for it in part['items']:
            if it['page'] not in index_of:
                sys.exit(f"{it['ar']}: page {it['page']} is not in the book")
            items.append({'ar': it['ar'], 'sv': it['sv'], 'page': index_of[it['page']]})
        parts.append({'ar': part['ar'], 'sv': part['sv'], 'page': index_of[part['page']], 'items': items})

    write_index(book, spec, cover, pages, parts)
    size = sum(os.path.getsize(os.path.join(out, p['file'])) for p in pages)
    print(f'{book}: {len(pages)} pages, {size / 1e6:.1f} MB, {sum(len(p["items"]) for p in parts)} entries')


def write_index(book, spec, cover, pages, parts):
    """assets/alhan/index.ts lists every book in assets/alhan; this one is (re)written into it."""
    books = {}
    path = os.path.join(OUT, 'books.json')
    if os.path.exists(path):
        with open(path, encoding='utf-8') as f:
            books = json.load(f)
    books[book] = {
        'id': book, 'ar': spec['ar'], 'sv': spec['sv'], 'subAr': spec['subAr'], 'subSv': spec['subSv'],
        'source': spec['source'], 'cover': {'file': 'cover.webp', 'w': cover.width, 'h': cover.height}, 'pages': pages, 'parts': parts,
    }
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(books, f, ensure_ascii=False, indent=1)

    lines = [
        '// Generated by scripts/alhan_pages.py. Do not edit.',
        "import type { AlhanBook } from '../../src/lib/types';",
        '',
        "type Img = { file: string; w: number; h: number };",
        "type Stored = Omit<AlhanBook, 'pages' | 'cover'> & { cover: Img; pages: (Omit<AlhanBook['pages'][number], 'src'> & { file: string })[] };",
        "const stored: Record<string, Stored> = require('./books.json');",
        '',
        '// The page images, bundled as assets: the book opens without a connection.',
        'const images: Record<string, Record<string, number>> = {',
    ]
    for b in books.values():
        lines.append(f"  '{b['id']}': {{")
        lines += [f"    '{f}': require('./{b['id']}/{f}')," for f in [b['cover']['file']] + [p['file'] for p in b['pages']]]
        lines.append('  },')
    lines += [
        '};',
        '',
        'export const alhanBooks: AlhanBook[] = Object.values(stored).map((b) => ({',
        '  ...b,',
        "  cover: { src: images[b.id][b.cover.file], w: b.cover.w, h: b.cover.h },",
        '  pages: b.pages.map(({ file, ...p }) => ({ ...p, src: images[b.id][file] })),',
        '}));',
        '',
    ]
    with open(os.path.join(OUT, 'index.ts'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))


if __name__ == '__main__':
    main()
