#!/usr/bin/env python3
"""Check the Swedish Synaxarium and write its index.

The translation lives in content/synaxarium-sv/, one Coptic month to a file
(01.synax for Tout ... 13.synax for Nasie): day → {"titles": [...], "paras": [...]},
a paragraph starting "# " a heading. See GLOSSARY.md there for the names and terms.
This checks each file (every day there, nothing left in English, the glossary's
forms used) and writes index.ts, which the app reads the translated months from.

Usage:
    python3 scripts/synax_sv.py
"""

import json
import os
import re
import sys

DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'content', 'synaxarium-sv')
DAYS = {m: 30 for m in range(1, 13)} | {13: 6}

# English left in, or a form the glossary replaces with another.
SUSPECT = [
    (r'\b(the|and|of|was|were|with|this|which|his|her|their)\b', 'English word'),
    (r'\bSt\.|\bSaint\b', 'English "St."; the glossary has "den helige"'),
    (r'\bAntonios\b|\bAntony\b', 'Antonius'), (r'\bAthanasius\b', 'Athanasios'), (r'\bMacarius\b', 'Makarios'),
    (r'\bBasilius\b|\bBasil\b', 'Basileios'), (r'\bDioscorus\b', 'Dioskoros'), (r'\bPachomius\b', 'Pachomios'),
    (r'\bGeorge\b', 'Georgios'), (r'\bTheodore\b', 'Theodoros'), (r'\bScetis\b|\bShiheet\b|\bScete\b', 'Sketis'),
    (r'\bZacharias\b', 'Sakarias'), (r'\bElijah\b', 'Elia'), (r'\bIsaiah\b', 'Jesaja'), (r'\bMoses\b', 'Mose'),
]


def main():
    months = []
    problems = 0
    for m in range(1, 14):
        path = os.path.join(DIR, f'{m:02d}.synax')
        if not os.path.exists(path):
            continue
        months.append(m)
        data = json.load(open(path, encoding='utf-8'))
        missing = [d for d in range(1, DAYS[m] + 1) if str(d) not in data]
        if missing:
            print(f'{m:02d}: days missing: {missing}')
            problems += 1
        for day, e in data.items():
            if not e.get('titles') or not e.get('paras'):
                print(f'{m:02d}/{day}: no titles or no text')
                problems += 1
            for text in e.get('titles', []) + e.get('paras', []):
                for pat, why in SUSPECT:
                    for hit in re.finditer(pat, text):
                        print(f'{m:02d}/{day}: {why}: …{text[max(0, hit.start() - 30):hit.end() + 30]}…')
                        problems += 1
    with open(os.path.join(DIR, 'index.ts'), 'w', encoding='utf-8') as f:
        f.write('// Generated by scripts/synax_sv.py. Do not edit.\n')
        f.write('// The Synaxarium in Swedish, one Coptic month to a file; a month not translated yet is not here.\n')
        f.write('export const synaxSvAssets: Record<number, number> = {\n')
        for m in months:
            f.write(f"  {m}: require('./{m:02d}.synax'),\n")
        f.write('};\n')
    print(f'{len(months)} months translated; {problems} problems')
    sys.exit(1 if problems else 0)


if __name__ == '__main__':
    main()
